#!/usr/bin/env python3
"""Export the search dictionary from firmware/dictionary-source.json."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]

def generate(source):
    revision = json.loads((ROOT / 'firmware/dictionary-source.json').read_text())['ref']
    if subprocess.run(['git', 'cat-file', '-e', f'{revision}:src/tables.rs'], cwd=source, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode:
        subprocess.run(['git', 'fetch', '--depth', '1', 'origin', revision], cwd=source, check=True)
    text = subprocess.check_output(['git', 'show', f'{revision}:src/tables.rs'], cwd=source, text=True)
    # Dictionary form is inflection index 5 in the shared Engine tables.
    endings = {}
    for suffix, name in [('', 'CONJUGATE_GODAN_MAP'), ('i', 'CONJUGATE_KAMI_MAP'), ('e', 'CONJUGATE_SIMO_MAP')]:
        body = re.search(r'pub const ' + name + r':.*?= &\[(.*?)\n\];', text, re.S)
        for row, values in re.findall(r'\(\s*"([^"]*)",\s*&\[(.*?)\]\s*,?\s*\)', body[1], re.S):
            endings[row + suffix] = re.findall(r'"([^"]*)"', values)[5]
    for row, name in [('sh', 'SAHEN_LIST'), ('kh', 'KAHEN_LIST')]:
        body = re.search(r'pub const ' + name + r':.*?= &\[(.*?)\n\];', text, re.S)
        endings[row] = re.findall(r'"([^"]*)"', body[1])[5]
    if not endings or endings.get('k') != 'く':
        raise ValueError('Incomplete verb inflection tables')
    entries = []
    for kind, name in enumerate(['USERS_MAP', 'ABSTRACT_MAP', 'ABSTRACT_MAP_LEFT', 'ABSTRACT_MAP_RIGHT', 'VERB_MAP']):
        if re.search(r'pub const ' + name + r':[^\n]*= &\[\];', text):
            continue
        body = re.search(r'pub const ' + name + r':.*?= &\[(.*?)\n\];', text, re.S)
        if not body:
            raise ValueError(f'Missing dictionary table: {name}')
        pattern = r'\("([^"]*)", &\["([^"]*)", "([^"]*)"\]\)' if kind == 4 else r'\("([^"]*)", "([^"]*)"\)'
        for match in re.findall(pattern, body[1]):
            entries.append(dict(kind=kind, key=match[0], value=match[1], row=match[2] if kind == 4 else '', context=0, hidden=False))
    if len(entries) < 1000:
        raise ValueError('Unexpectedly incomplete dictionary export')
    if any(entry['kind'] == 4 and entry['row'] not in endings for entry in entries):
        raise ValueError('Dictionary contains an unsupported verb inflection row')
    (ROOT / 'site/dictionary.json').write_text(json.dumps(dict(engine=revision, entries=entries), ensure_ascii=False, separators=(',', ':')) + '\n')
    (ROOT / 'site/verb-endings.js').write_text('// Generated by scripts/generate-dictionary.py from the pinned Engine tables.\nexport const verbEndings = ' + json.dumps(endings, ensure_ascii=False, indent=2) + ';\n')
    print(f'Exported {len(entries)} built-in entries')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, default=ROOT / '.build/Mejiro_Engine')
    generate(parser.parse_args().source_dir)
